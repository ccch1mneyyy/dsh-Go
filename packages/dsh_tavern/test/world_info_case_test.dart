import 'package:dsh_tavern/src/worldinfo/world_info_case.dart';
import 'package:test/test.dart';

void main() {
  test('world info lowercase covers fixed Unicode 17 family mappings and boundaries', () {
    expect(_unicode17FamilyPairs, hasLength(166));
    for (final (upper, lower) in _unicode17FamilyPairs) {
      expect(
        lowercaseWorldInfoPlain(String.fromCharCode(upper)),
        String.fromCharCode(lower),
        reason: upper.toRadixString(16),
      );
    }
    final lowercase = String.fromCharCodes(_unicode17FamilyPairs.map((pair) => pair.$2));
    expect(lowercaseWorldInfoPlain(lowercase), lowercase);
    const unchanged =
        '\u139f\u13f6\u13f7\u13fe\u13ff'
        '\u1c8f\u1cbb\u1cbc\u1cc0'
        '\u{1e8ff}\u{1e944}\u{1e950}\u{1e95e}\u{1e95f}';
    expect(lowercaseWorldInfoPlain(unchanged), unchanged);
    const mixed = <(String, String)>[
      ('\u13a0 A\u03a3 \u0130', '\uab70 a\u03c2 i\u0307'),
      ('\u1c90 A\u0345\u03a3\u0345A \u{1e900}', '\u10d0 a\u0345\u03c3\u0345a \u{1e922}'),
    ];
    for (final (input, expected) in mixed) {
      expect(lowercaseWorldInfoPlain(input), expected);
    }
    // Isolated code units stay isolated; only the final complete pair is Adlam.
    // This is a helper assertion, not a UTF-8/file round trip.
    final unpaired = String.fromCharCodes([0xd83a, 0x21, 0xdd00, 0xd800, 0x20, 0xdc00, 0x13a0, 0xd83a, 0xdd00]);
    expect(lowercaseWorldInfoPlain(unpaired).codeUnits, [
      0xd83a,
      0x21,
      0xdd00,
      0xd800,
      0x20,
      0xdc00,
      0xab70,
      0xd83a,
      0xdd22,
    ]);
  });

  test('world info lowercase keeps original context and UTF-16 code units', () {
    // Literal expected values from Unicode default SpecialCasing and the
    // retained fixed-ST/Node design evidence; no candidate-derived oracle.
    const cases = <(String, String)>[
      ('CAP海🌊', 'cap海🌊'),
      ('\u03a3', '\u03c3'),
      ('\u039f\u03a3\u0391', '\u03bf\u03c3\u03b1'),
      ('\u03a3\u03a3', '\u03c3\u03c2'),
      ('\u0345\u03a3', '\u0345\u03c3'),
      ('A\u0345\u03a3', 'a\u0345\u03c2'),
      ('A\u03a3\u0345', 'a\u03c2\u0345'),
      ('A\u03a3\u0345A', 'a\u03c3\u0345a'),
      ('A\u03a3\u0001B', 'a\u03c2\u0001b'),
      ('\u0130\u03a3', 'i\u0307\u03c2'),
      ('I\u0131\u0130i', 'i\u0131i\u0307i'),
      ('J\u0301', 'j\u0301'),
      ('\u0130\u0307', 'i\u0307\u0307'),
      ('\u03bf\u03c3 \u03bf\u03c2', '\u03bf\u03c3 \u03bf\u03c2'),
      ('\u{10400}\u03a3', '\u{10428}\u03c2'),
    ];
    for (final (input, expected) in cases) {
      expect(lowercaseWorldInfoPlain(input), expected, reason: input.codeUnits.toString());
    }
    // This checks only the new conversion helper, not UTF-8/file persistence.
    final unpaired = String.fromCharCodes([0xd800, 0x41, 0x03a3, 0xdc00]);
    expect(lowercaseWorldInfoPlain(unpaired).codeUnits, [0xd800, 0x61, 0x03c2, 0xdc00]);
  });
}

