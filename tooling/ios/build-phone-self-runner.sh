#!/usr/bin/env bash
# Prepare the shared Rust CoreDevice/XCTest owner for the iOS app.
# --check runs portable Rust tests without an Apple SDK or enabling the app feature.
set -euo pipefail
ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/../.." && pwd -P)"
NATIVE="$ROOT/tooling/ios/phone-self-runner"
OUT="$ROOT/app/ios/PhoneSelfRunnerNative"
MODE="${1:-build}"
if [[ "$MODE" != build && "$MODE" != --check ]]; then
  printf 'Usage: %s [--check]\n' "$0" >&2
  exit 2
fi
command -v cargo >/dev/null || { printf 'Install rustup first; this component uses the pinned rust-toolchain.toml.\n' >&2; exit 1; }
python3 -I -B "$NATIVE/prepare_upstream.py"
cd "$NATIVE"
if [[ "$MODE" == --check ]]; then
  cargo test --locked --target-dir "$NATIVE/target"
  cargo build --locked --target-dir "$NATIVE/target"
  if [[ "$(uname -s)" == Darwin ]]; then
    system=(-framework Security -framework CoreFoundation -framework SystemConfiguration -liconv -lresolv)
  else
    system=(-ldl -lpthread -lm)
  fi
  "${CC:-cc}" -std=c11 -Wall -Wextra -Werror -I "$NATIVE/include" "$NATIVE/tests/ffi-smoke.c" \
    "$NATIVE/target/debug/libdsh_phone_self_runner.a" "${system[@]}" -o "$NATIVE/target/ffi-smoke"
  "$NATIVE/target/ffi-smoke"
  python3 -I -B "$NATIVE/tests/test_build_inputs.py"
  exit
fi
[[ "$(uname -s)" == Darwin ]] || { printf 'Apple library builds require macOS and Xcode; use --check for portable tests.\n' >&2; exit 1; }
command -v xcrun >/dev/null || { printf 'Select an installed Xcode before building.\n' >&2; exit 1; }
[[ ! -L "$OUT" ]] || { printf 'Refusing a symlinked output directory.\n' >&2; exit 1; }
mkdir -p "$OUT"
STAGE="$(mktemp -d "$OUT/.build.XXXXXX")"
cleanup() { [[ "$STAGE" == "$OUT"/.build.* ]] && rm -rf -- "$STAGE"; }
trap cleanup EXIT
for spec in 'aarch64-apple-ios:iphoneos:arm64' 'aarch64-apple-ios-sim:iphonesimulator:arm64' 'x86_64-apple-ios:iphonesimulator:x86_64'; do
  IFS=: read -r target platform arch <<< "$spec"
  rustup target add "$target"
  # Emit native objects: the selected Xcode may not understand the pinned
  # Rust toolchain's newer LLVM bitcode.
  CARGO_PROFILE_RELEASE_LTO=false cargo build --release --locked --target "$target" --target-dir "$NATIVE/target"
  mkdir -p "$STAGE/$platform/$arch"
  cp "$NATIVE/target/$target/release/libdsh_phone_self_runner.a" "$STAGE/$platform/$arch/"
done
cp "$NATIVE/.upstream/LICENSE.txt" "$STAGE/LICENSE.idevice.txt"
cp "$NATIVE/source-pins.json" "$STAGE/SOURCE.json"
cargo metadata --locked --format-version 1 > "$STAGE/cargo-metadata.json"
python3 -I -B "$NATIVE/license_inventory.py" "$STAGE/cargo-metadata.json" \
  "$STAGE/THIRD_PARTY_CRATES.json" "$STAGE/NOTICES.txt"
python3 -I -B "$NATIVE/license_inventory.py" --verify "$STAGE"
cat > "$STAGE/PhoneSelfRunner.xcconfig" <<'CONFIG'
// Generated by tooling/ios/build-phone-self-runner.sh. Capabilities are opt-in in the app.
DSH_PHONE_SELF_RUNNER_ENABLED = YES
SWIFT_ACTIVE_COMPILATION_CONDITIONS = $(inherited) DSH_PHONE_SELF_RUNNER
DSH_PHONE_SELF_RUNNER_LIBRARY = $(SRCROOT)/PhoneSelfRunnerNative/$(PLATFORM_NAME)/$(CURRENT_ARCH)/libdsh_phone_self_runner.a
OTHER_LDFLAGS = $(inherited) -force_load "$(DSH_PHONE_SELF_RUNNER_LIBRARY)" -framework Security -framework CoreFoundation -framework SystemConfiguration -lc++ -lresolv -lz -liconv
CONFIG
# Publish the opt-in config last: a failed first build cannot enable missing slices.
for platform in iphoneos iphonesimulator; do
  mkdir -p "$OUT/$platform"
  cp -R "$STAGE/$platform/". "$OUT/$platform/"
done
cp "$STAGE/LICENSE.idevice.txt" "$STAGE/THIRD_PARTY_CRATES.json" "$STAGE/NOTICES.txt" "$STAGE/SOURCE.json" "$OUT/"
cp "$STAGE/PhoneSelfRunner.xcconfig" "$OUT/PhoneSelfRunner.xcconfig"
printf 'Shared CoreDevice/XCTest native owner prepared; all sensitive capabilities require in-app opt-in.\n'
