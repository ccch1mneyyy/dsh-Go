#!/usr/bin/env python3
"""Generate napi-rename.h from the pinned Node 24.22.1 N-API headers, or check it is current."""

import argparse
import hashlib
from pathlib import Path
import re
import sys


HERE = Path(__file__).resolve().parent
OUTPUT = HERE / 'napi-rename.h'
HEADERS = {
    'src/js_native_api.h': '82d3708ce120f8000ec34d72e1aa70b0d7d8a43027986293681374a71b2cb840',
    'src/node_api.h': '2d4560831e525b47b060ec8a0864ab73993df9e20215ce9f0fe7b24cd31af32a',
}
# Not N-API: the two libuv error helpers the linked publication binding calls. libuv itself stays private.
EXTRA = ['uv_err_name', 'uv_translate_sys_error']
DECLARATION = re.compile(r'\bNAPI_EXTERN\b[^;{}]*?\b((?:napi|node_api)_\w+)\s*\(')


def render(source):
    names = set(EXTRA)
    for name, pin in HEADERS.items():
        data = (source / name).read_bytes()
        if hashlib.sha256(data).hexdigest() != pin:
            raise RuntimeError(f'Node header SHA256 mismatch: {name}')
        text = re.sub(r'/\*.*?\*/|//[^\n]*', ' ', data.decode(), flags=re.S)
        names.update(DECLARATION.findall(text))
    lines = [f'#define {name} dsh_{name}' for name in sorted(names)]
    return ('// Generated by gen-napi-rename.py from Node 24.22.1 src/js_native_api.h and src/node_api.h.\n'
            '// Force-include (-include) in all of libnode and everything that links against it.\n'
            '#ifndef DSH_NAPI_RENAME_H_\n#define DSH_NAPI_RENAME_H_\n'
            + '\n'.join(lines) + '\n#endif  // DSH_NAPI_RENAME_H_\n')


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--source', required=True, type=Path, help='Node 24.22.1 source')
    parser.add_argument('--check', action='store_true', help='Fail if the committed header differs')
    args = parser.parse_args()
    text = render(args.source)
    if args.check:
        if not OUTPUT.is_file() or OUTPUT.read_text() != text:
            sys.exit(f'{OUTPUT} is stale; run this script without --check')
    else:
        OUTPUT.write_text(text)


if __name__ == '__main__':
    main()
