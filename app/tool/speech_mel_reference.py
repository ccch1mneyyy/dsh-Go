#!/usr/bin/env python3
"""Generate NumPy-only smart-turn Whisper reference vectors.

python app/tool/speech_mel_reference.py [--check-transformers]
The optional check also compares every feature with transformers 4.51.3.
Sources: pipecat-ai/smart-turn inference.py; transformers WhisperFeatureExtractor.
"""

import argparse
from pathlib import Path

import numpy as np


SAMPLES, FFT, HOP, MELS = 128000, 400, 160, 80


def waveform(name):
    i = np.arange(SAMPLES, dtype=np.int64)
    if name == "padded":
        values = (((i * 7919) % 65536) - 32768).astype(np.float32) / 32768
        values[:96000] = 0
        values[-1] = 0.75
        return values
    if name == "varying":
        # Integer arithmetic gives identical inputs on Python and the JVM.
        carrier = (((i * 97) % 4096) - 2048).astype(np.float32)
        envelope = ((i // 1600) % 7 + 1).astype(np.float32)
        return carrier * envelope / 32768 + np.float32(0.125)
    return np.zeros(SAMPLES, dtype=np.float32)


def log_mel(audio):
    # The upstream extractor normalizes after the caller has left-padded to 8 s.
    audio = ((audio - audio.mean()) / np.sqrt(audio.var() + np.float32(1e-7))).astype(np.float32)
    padded = np.pad(audio, (FFT // 2, FFT // 2), mode="reflect")
    frames = np.lib.stride_tricks.sliding_window_view(padded, FFT)[::HOP][:-1]
    window = np.hanning(FFT + 1)[:-1]
    power = np.abs(np.fft.rfft(frames * window, n=FFT, axis=-1)) ** 2

    max_mel = 15 + np.log(8) / (np.log(6.4) / 27)
    mel = np.linspace(0, max_mel, MELS + 2)
    hz = np.where(mel < 15, mel * (200 / 3), 1000 * np.exp((mel - 15) * np.log(6.4) / 27))
    frequencies = np.linspace(0, 8000, FFT // 2 + 1)
    down = (frequencies[:, None] - hz[:-2]) / (hz[1:-1] - hz[:-2])
    up = (hz[2:] - frequencies[:, None]) / (hz[2:] - hz[1:-1])
    filters = np.maximum(0, np.minimum(down, up)) * (2 / (hz[2:] - hz[:-2]))
    features = np.log10(np.maximum(power @ filters, 1e-10)).T.astype(np.float32)
    features = np.maximum(features, features.max() - np.float32(8))
    return (features + np.float32(4)) / np.float32(4)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check-transformers", action="store_true")
    args = parser.parse_args()
    output = Path(__file__).resolve().parents[1] / "android/app/src/test/resources/speech/whisper_mel.csv"
    output.parent.mkdir(parents=True, exist_ok=True)
    rows = ["# waveform,mel,frame,value; generated by app/tool/speech_mel_reference.py"]
    for name in ("zero", "padded", "varying"):
        audio = waveform(name)
        features = log_mel(audio)
        if args.check_transformers:
            from transformers import WhisperFeatureExtractor

            extractor = WhisperFeatureExtractor(chunk_length=8)
            expected = extractor(
                audio, sampling_rate=16000, return_tensors="np", padding="max_length",
                max_length=SAMPLES, truncation=True, do_normalize=True,
            ).input_features[0]
            error = np.max(np.abs(features - expected))
            np.testing.assert_allclose(features, expected, atol=2e-5, rtol=0)
            print(f"{name}: transformers max error {error:.9g}")
        # Every time frame and mel band, plus boundary frames in every band.
        positions = {(time * 17 % MELS, time) for time in range(800)}
        positions.update((band, time) for band in range(MELS) for time in (0, 1, 599, 600, 601, 798, 799))
        for band, time in sorted(positions):
            rows.append(f"{name},{band},{time},{features[band, time]:.9g}")
    output.write_text("\n".join(rows) + "\n", encoding="utf-8")
    print(f"Wrote {output} ({len(rows) - 1} reference values)")


if __name__ == "__main__":
    main()
