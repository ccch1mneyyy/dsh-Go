#!/usr/bin/env python3
"""Generate constants and Unicode-15 NFC/casefold tables; no network needed.

The rules file is copied verbatim from dsh-go-market/schema/pet-pack.rules.json.
Use CPython 3.12 (unicodedata 15.0.0), the same Unicode database as market CI.
Unicode source/license: https://www.unicode.org/Public/15.0.0/ucd/ and
unicode-15.0-LICENSE.txt. Regenerate, then `dart format` the two output files.
"""
import base64
import hashlib
import json
from pathlib import Path
import unicodedata as u
import zlib

APP = Path(__file__).resolve().parents[1]
RULES = APP / 'tool/pet-pack.rules.json'
EXPECTED = 'e14e27013d7a766293bdf385dcab966dea22afcb4f995b88d15ef07124922e04'
raw = RULES.read_bytes()
assert hashlib.sha256(raw).hexdigest() == EXPECTED, 'Rules changed: review both CI and Dart before updating the pin'
assert u.unidata_version == '15.0.0', 'Use CPython 3.12 / Unicode 15.0.0'
limits = json.loads(raw)['limits']
names = {
    'petJsonCap': 'packJsonBytes', 'petSheetByteCap': 'sheetBytes',
    'petSheetCountCap': 'sheetCount', 'petTotalSheetByteCap': 'totalSheetBytes',
    'petSheetSideCap': 'sheetSide', 'petSheetDecodedCap': 'sheetDecodedBytes',
    'petSheetNameCap': 'sheetNameCharacters', 'petArchiveByteCap': 'archiveBytes',
    'petArchiveExpandedCap': 'archiveExpandedBytes', 'petArchiveEntryCap': 'archiveEntries',
    'petJsonDepthCap': 'jsonDepth',
    'petPngMetadataChunkCap': 'pngMetadataChunkBytes',
    'petPngMetadataTotalCap': 'pngMetadataTotalBytes',
}
(APP / 'lib/pets/pet_pack_rules.g.dart').write_text(
    '// GENERATED by tool/generate_pet_validation_data.py. Do not edit.\n'
    f"const petPackRulesSha256 = '{EXPECTED}';\n" +
    ''.join(f'const {name} = {limits[key]};\n' for name, key in names.items()), encoding='utf-8')

decompositions, classes, compositions, folds = {}, {}, {}, {}
for cp in range(0x110000):
    ch = chr(cp)
    d = u.decomposition(ch)
    if d and not d.startswith('<'):
        points = [int(p, 16) for p in d.split()]
        decompositions[str(cp)] = points
        if len(points) == 2 and u.normalize('NFC', ''.join(map(chr, points))) == ch:
            compositions[f'{points[0]},{points[1]}'] = cp
    if c := u.combining(ch):
        classes[str(cp)] = c
    if ch.casefold() != ch:
        folds[str(cp)] = list(map(ord, ch.casefold()))
data = json.dumps([decompositions, classes, compositions, folds], ensure_ascii=True,
                  sort_keys=True, separators=(',', ':')).encode()
encoded = base64.b64encode(zlib.compress(data, 9)).decode()
(APP / 'lib/pets/pet_unicode_data.g.dart').write_text(
    '// GENERATED by tool/generate_pet_validation_data.py. Do not edit.\n'
    '// Unicode 15.0.0, CPython unicodedata; see tool/unicode-15.0-LICENSE.txt.\n'
    "const petUnicodeVersion = '15.0.0';\n"
    f"const petUnicodeDataSha256 = '{hashlib.sha256(data).hexdigest()}';\n"
    '// Python str.strip/isspace differs from Dart trim (notably U+001C and U+FEFF).\n'
    'const petUnicodeWhitespace = <int>{' + ', '.join(str(cp) for cp in range(0x110000) if chr(cp).isspace()) + '};\n'
    'const petUnicodeData =\n' +
    ''.join("    '" + encoded[i:i+100] + "'\n" for i in range(0, len(encoded), 100)) +
    '    ;\n', encoding='utf-8')
print(f'rules={EXPECTED}; unicode={u.unidata_version}; table={len(data)} bytes / {len(encoded)} base64 chars')
