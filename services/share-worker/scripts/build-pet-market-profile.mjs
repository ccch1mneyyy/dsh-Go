#!/usr/bin/env node
// A staging receipt is valid only for the source that performed its checks.
// Hash all Worker TS source, rather than a manually maintained list of validator
// helpers: vocabulary, limits, JSON IO, ordering and future helpers are covered.
import { createHash } from 'node:crypto';
import { existsSync, mkdirSync, readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { dirname, join, relative, resolve, sep } from 'node:path';
import { fileURLToPath } from 'node:url';

const script = fileURLToPath(import.meta.url);
const workerRoot = resolve(dirname(script), '..');
const hash = value => createHash('sha256').update(value).digest('hex');

export function petMarketProfile(worker = workerRoot) {
  const src = join(worker, 'src');
  const sources = readdirSync(src, { recursive: true, withFileTypes: true })
    .filter(entry => entry.isFile() && entry.name.endsWith('.ts'))
    .map(entry => relative(worker, join(entry.parentPath, entry.name)).split(sep).join('/'))
    .filter(path => !path.split('/').includes('generated'));
  const paths = [...sources, 'scripts/build-pet-market-profile.mjs', 'scripts/build-site.mjs',
    'package.json', 'package-lock.json', 'tsconfig.json'].sort();
  const inputs = paths.map(path => [path, hash(readFileSync(join(worker, path)))]);
  const fingerprint = hash(JSON.stringify(inputs));
  const text = '// GENERATED by scripts/build-pet-market-profile.mjs. Do not edit.\n' +
    `export const PET_MARKET_PROFILE = '${fingerprint}';\n`;
  return { fingerprint, inputs, text };
}

export function writePetMarketProfile(worker = workerRoot, check = false) {
  const result = petMarketProfile(worker);
  const target = join(worker, 'src/generated/pet-market-profile.ts');
  if (check) {
    if (!existsSync(target) || readFileSync(target, 'utf8') !== result.text)
      throw new Error('pet-market profile is stale: run npm run build');
  } else {
    mkdirSync(dirname(target), { recursive: true });
    writeFileSync(target, result.text);
  }
  return result;
}

if (process.argv[1] && resolve(process.argv[1]) === script) {
  writePetMarketProfile(workerRoot, process.argv.includes('--check'));
}
